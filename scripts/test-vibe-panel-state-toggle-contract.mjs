const viewTemplate = parse(viewSource, { filename: viewPath }).descriptor.template?.content || ''
const mainToggle = viewTemplate.indexOf('class="main-head-side-toggle"')
const mainTitle = viewTemplate.indexOf('<h1>{{ headTitle }}</h1>')
assert.ok(mainToggle >= 0 && mainToggle < mainTitle, 'collapsed toggle must render immediately before the main title')
const infoToggle = viewTemplate.indexOf('class="info-rail-toggle"')
const workspaceToggle = viewTemplate.indexOf('class="workspace-window-toggle window-toggle-anchor"')
assert.ok(infoToggle >= 0 && workspaceToggle === -1, 'Settings2 must remain the only right-side main header entry this release')
const conversationPaneStart = viewTemplate.indexOf('<div class="main-conversation-pane">')
const mainHeadStart = viewTemplate.lastIndexOf('<header', infoToggle)
const conversationStart = viewTemplate.indexOf('<section v-if="currentView === \'conversation\'" class="conversation">')
assert.ok(mainHeadStart >= 0 && mainHeadStart < conversationPaneStart && conversationPaneStart < conversationStart, 'main header must stay anchored to the whole main content area instead of shrinking with the info panel')
